// Builds src/geo/mapdata.ts: coastlines and rivers as SVG paths, from Natural Earth (public domain) via the
// world-atlas package and a bundled rivers file. Run with: node scripts/build-maps.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';

const SA = { lon0: 60, lat1: 38, scale: 17, cosLat: Math.cos((21 * Math.PI) / 180) };
const WORLD = { lon0: -180, lat1: 80, scale: 2.7 };
const pSA = (lon, lat) => [(lon - SA.lon0) * SA.cosLat * SA.scale, (SA.lat1 - lat) * SA.scale];
const pW = (lon, lat) => [(lon - WORLD.lon0) * WORLD.scale, (WORLD.lat1 - lat) * WORLD.scale];

// Sutherland-Hodgman clip of a ring against a lon/lat box
function clipRing(ring, [x0, y0, x1, y1]) {
  const edges = [
    (p) => p[0] >= x0, (p) => p[0] <= x1, (p) => p[1] >= y0, (p) => p[1] <= y1,
  ];
  const cut = [
    (a, b) => [x0, a[1] + ((b[1] - a[1]) * (x0 - a[0])) / (b[0] - a[0])],
    (a, b) => [x1, a[1] + ((b[1] - a[1]) * (x1 - a[0])) / (b[0] - a[0])],
    (a, b) => [a[0] + ((b[0] - a[0]) * (y0 - a[1])) / (b[1] - a[1]), y0],
    (a, b) => [a[0] + ((b[0] - a[0]) * (y1 - a[1])) / (b[1] - a[1]), y1],
  ];
  let out = ring;
  for (let e = 0; e < 4; e++) {
    const input = out;
    out = [];
    if (!input.length) break;
    let prev = input[input.length - 1];
    for (const cur of input) {
      const ci = edges[e](cur), pi = edges[e](prev);
      if (ci) { if (!pi) out.push(cut[e](prev, cur)); out.push(cur); }
      else if (pi) out.push(cut[e](prev, cur));
      prev = cur;
    }
  }
  return out;
}

function ringPath(ring, proj, minGap) {
  const pts = [];
  let last = null;
  for (const [lon, lat] of ring) {
    const q = proj(lon, lat);
    if (last && Math.hypot(q[0] - last[0], q[1] - last[1]) < minGap) continue;
    pts.push(q);
    last = q;
  }
  if (pts.length < 3) return '';
  return 'M' + pts.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L') + 'Z';
}

function landPath(file, box, proj, minGap) {
  const topo = JSON.parse(readFileSync(file, 'utf8'));
  const land = feature(topo, topo.objects.land);
  const polys = land.type === 'FeatureCollection' ? land.features.flatMap((f) => f.geometry.coordinates) : land.geometry.coordinates;
  let d = '';
  for (const poly of polys) {
    for (const ring of poly) {
      const r = box ? clipRing(ring, box) : ring;
      d += ringPath(r, proj, minGap);
    }
  }
  return d;
}

const SA_BOX = [52, 0, 104, 46];
const southLand = landPath('node_modules/world-atlas/land-50m.json', SA_BOX, pSA, 0.7);
const worldLand = landPath('node_modules/world-atlas/land-110m.json', null, pW, 0.9);

// Rivers
const rivers = JSON.parse(readFileSync('scripts/rivers-ne50m.geojson', 'utf8'));
const WANT = ['Indus', 'Sutlej', 'Chenab', 'Ganges', 'Yamuna', 'Brahmaputra', 'Narmada', 'Krishna'];
const riverPaths = {};
for (const f of rivers.features) {
  const name = f.properties.name;
  if (!WANT.includes(name)) continue;
  const lines = f.geometry.type === 'MultiLineString' ? f.geometry.coordinates : [f.geometry.coordinates];
  for (const line of lines) {
    const inBox = line.filter(([lon, lat]) => lon > 56 && lon < 100 && lat > 6 && lat < 40);
    if (inBox.length < 2) continue;
    const pts = [];
    let last = null;
    for (const [lon, lat] of inBox) {
      const q = pSA(lon, lat);
      if (last && Math.hypot(q[0] - last[0], q[1] - last[1]) < 1.2) continue;
      pts.push(q); last = q;
    }
    if (pts.length < 2) continue;
    riverPaths[name] = (riverPaths[name] ?? '') + 'M' + pts.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L');
  }
}

const out = `// Generated by scripts/build-maps.mjs from Natural Earth (public domain). Do not edit by hand.
export const SOUTH_ASIA_LAND = ${JSON.stringify(southLand)};
export const WORLD_LAND = ${JSON.stringify(worldLand)};
export const RIVERS: Record<string, string> = ${JSON.stringify(riverPaths)};
`;
writeFileSync('src/geo/mapdata.ts', out);
console.log('south asia land', southLand.length, 'bytes; world land', worldLand.length, 'bytes; rivers', Object.keys(riverPaths).join(', '));
